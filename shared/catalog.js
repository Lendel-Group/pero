export function genreById(id) {
  return GENRES.find((genre) => genre.id === id) ?? null;
}

export function subgenreById(id) {
  return SUBGENRES.find((item) => item.id === id) ?? null;
}

export function subgenresOf(genreId) {
  return SUBGENRES.filter((item) => item.genreId === genreId);
}

export function optionById(list, id) {
  return list.find((item) => item.id === id) ?? null;
}

export function sceneCountFor(pacingId) {
  return optionById(PACING, pacingId)?.scenes ?? 4;
}

export function lengthFor(lengthId) {
  return optionById(LENGTHS, lengthId) ?? LENGTHS[1];
}

/**
 * Тона, совместимые с выбранными поджанрами: пересечение, а если оно
 * пустое — объединение (тогда UI честно говорит, что общего тона нет).
 */
export function tonesFor(subgenreIds) {
  const rows = subgenreIds.map(subgenreById).filter(Boolean);
  if (rows.length === 0) return { tones: [], mode: "none" };
  let shared = [...rows[0].tones];
  for (const row of rows.slice(1)) shared = shared.filter((tone) => row.tones.includes(tone));
  if (shared.length > 0) return { tones: order(shared), mode: "intersection" };
  return { tones: order([...new Set(rows.flatMap((row) => row.tones))]), mode: "union" };
}

function order(tones) {
  return [...tones].sort((a, b) => TONES.indexOf(a) - TONES.indexOf(b));
}

function sub(id, genreId, name, blurb, incompatible, bridges, tones, writer) {
  return { id, genreId, name, blurb, incompatible, bridges, tones, writer: { name, ...writer } };
}
