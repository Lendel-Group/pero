/** Публичное описание агентов для интерфейса. */
export function agentDirectory() {
  const system = Object.values(AGENTS).map(({ id, name, role, description }) => ({ id, name, role, description }));
  const writers = SUBGENRES.map((item) => ({
    id: `writer:${item.id}`,
    name: item.writer.name,
    role: "GENRE_WRITER",
    genreId: item.genreId,
    description: item.writer.voice,
  }));
  return { system, writers };
}
